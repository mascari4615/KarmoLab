export const sourceCoasts = outlines.map(ring => ring.map(([x, y]) => [(x - 55) / 870, y / 580]));
export function sourceMask(width, height) {
  const mask = new Uint8Array(width * height);
  for (let y = 0; y < height; y++) {
    const v = Math.min(1 - Number.EPSILON, y / (height - 1));
    for (const ring of sourceCoasts) {
      const intersections = [];
      for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
        const [ax, ay] = ring[i], [bx, by] = ring[j];
        if ((ay > v) !== (by > v)) intersections.push((bx - ax) * (v - ay) / (by - ay) + ax);
      }
      intersections.sort((a, b) => a - b);
      for (let i = 0; i < intersections.length; i += 2) {
        for (let x = Math.max(0, Math.ceil(intersections[i] * width)); x < Math.min(width, Math.ceil(intersections[i + 1] * width)); x++) mask[y * width + x] = 1;
      }
    }
  }
  return mask;
}
export function sourceLand(u, v) {
  v = Math.min(1 - Number.EPSILON, v);
  return sourceCoasts.some(ring => {
    let inside = false;
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const [ax, ay] = ring[i], [bx, by] = ring[j];
      if ((ay > v) !== (by > v) && u < (bx - ax) * (v - ay) / (by - ay) + ax) inside = !inside;
    }
    return inside;
  });
}
